// Command sets: every architecture has its own range of command ids (DianaGroupInfo::m_commandId).
// x86 ids are DianaCommandId above, the others are generated enums starting at their base:
//   DianaA64CommandId in diana_gen_a64.h (A64 with all its extensions)
//   AArch32 (A32 and T32 share one set, the mnemonics are the same) - not implemented yet
// The ids are not stable between generator runs, compare them with the enum names only.
#define DIANA_CMD_SET_SHIFT     16
#define DIANA_CMD_SET(id)       ((unsigned long)(id) >> DIANA_CMD_SET_SHIFT)

#define DIANA_CMD_SET_X86       0
#define DIANA_CMD_SET_A64       1
#define DIANA_CMD_SET_A32       2

#define DIANA_A64_CMD_BASE      (DIANA_CMD_SET_A64 << DIANA_CMD_SET_SHIFT)
#define DIANA_A32_CMD_BASE      (DIANA_CMD_SET_A32 << DIANA_CMD_SET_SHIFT)

