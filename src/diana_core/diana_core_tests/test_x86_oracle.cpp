// one context, one stream: what an instruction leaves in the context's cache must not change the next one
static void test_x86_stream()
{
    // vaddps xmm0,xmm1,xmm2, then no instruction (0f 38 3c), then mov [rdi],r8w: the VEX path left its selector
    // (c5 xx) before the next instruction's bytes and a failed table walk rolled back into it: "lds ecx,[rdi]"
    static unsigned char code[] = {0xc5, 0xf0, 0x58, 0xc2, 0x0f, 0x38, 0x3c, 0xcc, 0x66, 0x44, 0x89, 0x07};
    DianaContext context;
    Diana_InitContext(&context, DIANA_MODE64);
    DianaMemoryStream stream;
    Diana_InitMemoryStream(&stream, code, sizeof(code));
    DianaParserResult result;
    DIANA_TEST_ASSERT(Diana_ParseCmd(&context, Diana_GetRootLine(), &stream.parent.parent.parent, &result) == DI_SUCCESS);
    DIANA_TEST_ASSERT(result.iFullCmdSize == 4);
    DIANA_TEST_ASSERT(Diana_ParseCmd(&context, Diana_GetRootLine(), &stream.parent.parent.parent, &result) == DI_ERROR);

    // the same through a new stream for each instruction, like a disassembler that seeks (Diana_ClearCache)
    unsigned char next[] = {0x0f, 0x38, 0x3c, 0xcc, 0xcc};
    Diana_ClearCache(&context);
    Diana_InitMemoryStream(&stream, code, 4);
    DIANA_TEST_ASSERT(Diana_ParseCmd(&context, Diana_GetRootLine(), &stream.parent.parent.parent, &result) == DI_SUCCESS);
    Diana_ClearCache(&context);
    Diana_InitMemoryStream(&stream, next, sizeof(next));
    DIANA_TEST_ASSERT(Diana_ParseCmd(&context, Diana_GetRootLine(), &stream.parent.parent.parent, &result) == DI_ERROR);
}

static int DecodeX86(int mode, const char * pHex, DianaParserResult * pResult)
{
    unsigned char bytes[32];
    SetBytes(pHex, bytes, sizeof(bytes));
    DianaContext context;
    Diana_InitContext(&context, DianaMode(mode));
    DianaMemoryStream stream;
    Diana_InitMemoryStream(&stream, bytes, sizeof(bytes));
    return Diana_ParseCmd(&context, Diana_GetRootLine(), &stream.parent.parent.parent, pResult);
}

// what the processor and the analyzer read: usedSize of the memory operands, iOperandSize, the error codes
static void test_x86_operand_fields()
{
    struct SizeRow
    {
        int mode;
        const char * pBytes;
        int operand;
        int usedSize;
    };
    // the memory size of the instruction, not of the register (was 16 for every xmm memory, 4 for m80)
    static const SizeRow sizes[] =
    {
        {64, "f30f100a", 1, 4},         // movss xmm1, m32
        {64, "f20f100a", 1, 8},         // movsd xmm1, m64
        {64, "660f120a", 1, 8},         // movlpd xmm1, m64
        {64, "660f38200a", 1, 8},       // pmovsxbw xmm1, m64
        {32, "db2c24", 0, 10},          // fld m80
        {64, "df20", 0, 10},            // fbld m80
        {32, "0f600e", 1, 4},           // punpcklbw mm1, m32
        {64, "0ff31e", 1, 8},           // psllq mm3, m64
        {32, "0fc70e", 0, 8},           // cmpxchg8b m64
        {64, "480fc70e", 0, 16},        // cmpxchg16b m128
        {64, "c5fc5801", 2, 32},        // vaddps ymm0, ymm0, m256
    };
    int failed = 0;
    for (size_t i = 0; i < sizeof(sizes)/sizeof(sizes[0]); ++i)
    {
        DianaParserResult result;
        int status = DecodeX86(sizes[i].mode, sizes[i].pBytes, &result);
        if (status || result.iLinkedOpCount <= sizes[i].operand ||
            result.linkedOperands[sizes[i].operand].usedSize != sizes[i].usedSize)
        {
            printf("x%d: %s: operand %d usedSize %d, expected %d (status %d)\n", sizes[i].mode, sizes[i].pBytes,
                   sizes[i].operand, status ? -1 : result.linkedOperands[sizes[i].operand].usedSize,
                   sizes[i].usedSize, status);
            ++failed;
        }
    }
    DIANA_TEST_ASSERT(!failed);

    // DianaParserResult::iOperandSize: 66, REX.W, the mode
    struct OperandSizeRow
    {
        int mode;
        const char * pBytes;
        int operandSize;
    };
    static const OperandSizeRow operandSizes[] =
    {
        {64, "98", 4}, {64, "6698", 2}, {64, "4898", 8},
        {32, "99", 4}, {32, "6699", 2},
        {16, "99", 2}, {16, "6699", 4},
        {64, "66480f6ec0", 8},          // movq xmm0, rax: the mandatory 66 is no operand size
        {64, "660f6ec0", 4},            // movd xmm0, eax
    };
    for (size_t i = 0; i < sizeof(operandSizes)/sizeof(operandSizes[0]); ++i)
    {
        DianaParserResult result;
        int status = DecodeX86(operandSizes[i].mode, operandSizes[i].pBytes, &result);
        if (status || result.iOperandSize != operandSizes[i].operandSize)
        {
            printf("x%d: %s: iOperandSize %d, expected %d (status %d)\n", operandSizes[i].mode, operandSizes[i].pBytes,
                   status ? -1 : result.iOperandSize, operandSizes[i].operandSize, status);
            ++failed;
        }
    }
    DIANA_TEST_ASSERT(!failed);

    // #UD rules return DI_INVALID_OPCODE: the processor reports it for LOCK (test_processor_invalid_lock)
    DianaParserResult result;
    DIANA_TEST_ASSERT(DecodeX86(32, "f041", &result) == DI_INVALID_OPCODE);       // lock inc ecx
    DIANA_TEST_ASSERT(DecodeX86(64, "f0f2468a00", &result) == DI_INVALID_OPCODE); // lock mov, F2 after it
    DIANA_TEST_ASSERT(DecodeX86(64, "f30ffdc1", &result) == DI_INVALID_OPCODE);   // F3 paddw
    DIANA_TEST_ASSERT(DecodeX86(64, "f00fc70e", &result) == DI_SUCCESS);          // lock cmpxchg8b [rsi]
    DIANA_TEST_ASSERT(result.iPrefix == DI_PREFIX_LOCK);
}

// a 3-byte VEX prefix cut by the end of the stream: the decoder stops (it looped)
static void test_x86_vex_end_of_stream()
{
    static unsigned char code32[] = {0xc4, 0xe2};
    static unsigned char code64[] = {0xc4, 0xe2};
    DianaContext context;
    DianaMemoryStream stream;
    DianaParserResult result;

    Diana_InitContext(&context, DIANA_MODE32);
    Diana_InitMemoryStream(&stream, code32, sizeof(code32));
    DIANA_TEST_ASSERT(Diana_ParseCmd(&context, Diana_GetRootLine(), &stream.parent.parent.parent, &result) != DI_SUCCESS);

    Diana_InitContext(&context, DIANA_MODE64);
    Diana_InitMemoryStream(&stream, code64, sizeof(code64));
    DIANA_TEST_ASSERT(Diana_ParseCmd(&context, Diana_GetRootLine(), &stream.parent.parent.parent, &result) != DI_SUCCESS);
}

