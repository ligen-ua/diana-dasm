// x86 rules found by tests/x86/compare.py against objdump; the text is arm_dump's (diana_core's MASM text with the
// lock/rep/repne of DianaParserResult::iPrefix in front), checked against objdump's by compare.py
struct X86TextRow
{
    int mode;                       // 16, 32, 64
    unsigned long long address;
    int length;
    const char * pBytes;            // hex
    const char * pText;
};

// words that are no instruction: the decoder must fail
struct X86InvalidRow
{
    int mode;
    const char * pBytes;
    const char * pReason;
};

static int DianaMode(int mode)
{
    return mode == 16 ? DIANA_MODE16 : mode == 32 ? DIANA_MODE32 : DIANA_MODE64;
}

// the bytes, then int3 up to 32 like compare.py: a decoder that reads too far sees cc, not the end of the buffer
static size_t SetBytes(const char * pHex, unsigned char * pBytes, size_t size)
{
    size_t count = strlen(pHex) / 2;
    for (size_t i = 0; i < count && i < size; ++i)
    {
        char digits[3] = {pHex[i * 2], pHex[i * 2 + 1], 0};
        pBytes[i] = (unsigned char)strtoul(digits, 0, 16);
    }
    for (size_t i = count; i < size; ++i)
        pBytes[i] = 0xCC;
    return count;
}

static std::string X86Text(diana::CMasmString * pText, DianaParserResult * pResult, unsigned long long address)
{
    static const char * prefixes[] = {"", "lock ", "rep ", "repne "};
    std::string text = pText->Assign(pResult, address);
    if (pResult->iPrefix > DI_PREFIX_NONE && pResult->iPrefix <= DI_PREFIX_REPN)
        text = prefixes[pResult->iPrefix] + text;
    return text;
}

// every row is checked and every failure printed, then the test fails
static void TestX86Rows(const X86TextRow * pRows, size_t count)
{
    diana::CMasmString text;
    int failed = 0;
    for (size_t i = 0; i < count; ++i)
    {
        unsigned char bytes[32];
        SetBytes(pRows[i].pBytes, bytes, sizeof(bytes));
        DianaContext context;
        Diana_InitContext(&context, DianaMode(pRows[i].mode));
        DianaMemoryStream stream;
        Diana_InitMemoryStream(&stream, bytes, sizeof(bytes));
        DianaParserResult result;
        int status = Diana_ParseCmd(&context, Diana_GetRootLine(), &stream.parent.parent.parent, &result);
        std::string actual = status ? std::string("<error>") : X86Text(&text, &result, pRows[i].address);
        if (status || result.iFullCmdSize != pRows[i].length || actual != pRows[i].pText)
        {
            printf("x%d: %s: expected %d \"%s\", got %d \"%s\"\n", pRows[i].mode, pRows[i].pBytes, pRows[i].length,
                   pRows[i].pText, status ? 0 : result.iFullCmdSize, actual.c_str());
            ++failed;
        }
    }
    DIANA_TEST_ASSERT(!failed);
}

static void TestX86Invalid(const X86InvalidRow * pRows, size_t count)
{
    diana::CMasmString text;
    int failed = 0;
    for (size_t i = 0; i < count; ++i)
    {
        unsigned char bytes[32];
        SetBytes(pRows[i].pBytes, bytes, sizeof(bytes));
        DianaContext context;
        Diana_InitContext(&context, DianaMode(pRows[i].mode));
        DianaMemoryStream stream;
        Diana_InitMemoryStream(&stream, bytes, sizeof(bytes));
        DianaParserResult result;
        int status = Diana_ParseCmd(&context, Diana_GetRootLine(), &stream.parent.parent.parent, &result);
        if (status == DI_SUCCESS)
        {
            printf("x%d: %s (%s): decoded as %d \"%s\"\n", pRows[i].mode, pRows[i].pBytes, pRows[i].pReason,
                   result.iFullCmdSize, X86Text(&text, &result, 0).c_str());
            ++failed;
        }
    }
    DIANA_TEST_ASSERT(!failed);
}

